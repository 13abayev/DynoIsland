'use strict';
// The bridge between the island page and Island's main process.
const { contextBridge, ipcRenderer } = require('electron');

const on = channel => cb => ipcRenderer.on(channel, (_e, data) => cb(data));

contextBridge.exposeInMainWorld('islandApi', {
  onState: on('state'),
  onNudge: on('nudge'),
  onToggle: on('toggle'),
  onBlur: on('blur'),
  onTunnels: on('tunnels'),
  onIdentify: on('identify'),
  displays: () => ipcRenderer.invoke('displays:list'),
  setDisplays: ids => ipcRenderer.invoke('displays:set', ids),
  identifyDisplays: () => ipcRenderer.invoke('displays:identify'),
  setInteractive: yes => ipcRenderer.send('interactive', !!yes),
  focusWindow: () => ipcRenderer.send('focus-window'),
  jump: key => ipcRenderer.invoke('jump', key),
  act: (key, action, arg) => ipcRenderer.invoke('act', key, action, arg),
  menu: () => ipcRenderer.send('menu'),
  connectStatus: () => ipcRenderer.invoke('connect:status'),
  connect: (target, on, arg) => ipcRenderer.invoke('connect:run', target, on, arg),
  setSettings: patch => ipcRenderer.invoke('settings:set', patch),
  refreshLimits: () => ipcRenderer.invoke('limits:refresh'),
  answer: (key, choice) => ipcRenderer.invoke('answer', key, choice),
  reply: (key, text) => ipcRenderer.invoke('reply', key, text),
  projects: () => ipcRenderer.invoke('quick:projects'),
  ask: (id, prompt, opts) => ipcRenderer.invoke('quick:ask', id, prompt, opts),
  clipboardText: () => ipcRenderer.invoke('clipboard:text'),
  copyText: text => ipcRenderer.invoke('copy-text', text),
  // clipboard history
  onClips: on('clips'),
  clips: () => ipcRenderer.invoke('clips:list'),
  clipText: id => ipcRenderer.invoke('clips:text', id),
  clipCopy: id => ipcRenderer.invoke('clips:copy', id),
  clipPaste: id => ipcRenderer.invoke('clips:paste', id),
  clipPin: (id, yes) => ipcRenderer.invoke('clips:pin', id, yes),
  clipRemove: id => ipcRenderer.invoke('clips:remove', id),
  clipClear: () => ipcRenderer.invoke('clips:clear'),
  clipSnippet: text => ipcRenderer.invoke('clips:snippet', text),
  clipOcr: id => ipcRenderer.invoke('clips:ocr', id),
  // media and sound
  onLevel: on('level'),
  mediaControl: action => ipcRenderer.invoke('media', action),
  setVolume: level => ipcRenderer.invoke('volume', level),
  speakerMute: yes => ipcRenderer.invoke('speaker-mute', yes),
  micMute: yes => ipcRenderer.invoke('mic-mute', yes),
  openLink: url => ipcRenderer.invoke('open-link', url),
  // notes, timers, focus, translate
  notes: () => ipcRenderer.invoke('notes:get'),
  saveNotes: data => ipcRenderer.invoke('notes:save', data),
  timerStart: (min, label) => ipcRenderer.invoke('timer:start', min, label),
  timerCancel: id => ipcRenderer.invoke('timer:cancel', id),
  focusStart: min => ipcRenderer.invoke('focus:start', min),
  focusStop: () => ipcRenderer.invoke('focus:stop'),
  onTranslation: on('translation'),
  copyToken: () => ipcRenderer.invoke('copy-token'),
  openExtensionFolder: () => ipcRenderer.invoke('open-extension-folder'),
});
